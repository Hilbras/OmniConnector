import { OmniConnectorError } from "./errors.js";
import type {
  AuditEvent,
  Capability,
  CreateOperationRequest,
  Health,
  IntegrationDetail,
  IntegrationSummary,
  NormalizedError,
  Operation,
} from "./types.js";
import { isTerminal } from "./types.js";

export const VERSION = "0.1.0";

export interface ClientOptions {
  /** Kernel API base URL, e.g. "https://connect.example.com" */
  baseUrl: string;
  /** Bearer token for the calling user or application */
  token: string;
  /** Per-request timeout in milliseconds (default 60 000) */
  timeoutMs?: number;
  /** Custom fetch, e.g. for testing or proxies (default: global fetch) */
  fetch?: typeof fetch;
}

export interface RequestOptions {
  /** Correlation ID sent as X-Request-ID; generated by the server when omitted */
  requestId?: string;
  signal?: AbortSignal;
}

export interface CreateOperationOptions extends RequestOptions {
  /**
   * Makes the request safe to retry: a repeat with the same key returns the
   * original operation instead of executing again. Strongly recommended for
   * operations with side effects.
   */
  idempotencyKey?: string;
}

export interface WaitOptions extends RequestOptions {
  /** Polling interval in milliseconds (default 1 000) */
  intervalMs?: number;
  /** Give up after this many milliseconds (default: no limit) */
  timeoutMs?: number;
}

interface Envelope {
  error?: NormalizedError & { requestId?: string };
}

/**
 * Client for the OmniConnector Kernel API v1.
 *
 * The client never retries on its own. Whether a retry is safe depends on the
 * operation, so the decision is left to the caller — use idempotency keys and
 * check `error.retryable` / the `unknown_outcome` state.
 */
export class OmniConnectorClient {
  readonly integrations: Integrations;
  readonly operations: Operations;
  readonly auditEvents: AuditEvents;

  private readonly baseUrl: string;
  private readonly token: string;
  private readonly timeoutMs: number;
  private readonly fetchImpl: typeof fetch;

  constructor(options: ClientOptions) {
    let url: URL;
    try {
      url = new URL(options.baseUrl);
    } catch {
      throw new TypeError(`invalid baseUrl: ${options.baseUrl}`);
    }
    if (url.protocol !== "https:" && url.protocol !== "http:") {
      throw new TypeError("baseUrl must use http or https");
    }
    if (!options.token) {
      throw new TypeError("token is required");
    }
    this.baseUrl = url.toString().replace(/\/+$/, "");
    this.token = options.token;
    this.timeoutMs = options.timeoutMs ?? 60_000;
    const f = options.fetch ?? globalThis.fetch;
    if (typeof f !== "function") {
      throw new TypeError("no fetch implementation available; pass options.fetch");
    }
    this.fetchImpl = f;

    this.integrations = new Integrations(this);
    this.operations = new Operations(this);
    this.auditEvents = new AuditEvents(this);
  }

  /** Liveness and kernel summary. Does not require authentication. */
  health(options?: RequestOptions): Promise<Health> {
    return this.request("GET", "/health", { ...options, auth: false });
  }

  /** Resolves when the kernel and its backing stores can serve traffic; throws otherwise */
  async ready(options?: RequestOptions): Promise<void> {
    await this.request("GET", "/ready", { ...options, auth: false });
  }

  /** @internal */
  async request<T>(
    method: string,
    path: string,
    options: RequestOptions & { body?: unknown; headers?: Record<string, string>; auth?: boolean } = {},
  ): Promise<T> {
    const headers: Record<string, string> = { Accept: "application/json", ...options.headers };
    if (options.auth !== false) {
      headers.Authorization = `Bearer ${this.token}`;
    }
    if (options.requestId) {
      headers["X-Request-ID"] = options.requestId;
    }
    let body: string | undefined;
    if (options.body !== undefined) {
      headers["Content-Type"] = "application/json";
      body = JSON.stringify(options.body);
    }

    const timeout = AbortSignal.timeout(this.timeoutMs);
    const signal = options.signal ? AbortSignal.any([options.signal, timeout]) : timeout;

    let response: Response;
    try {
      const init: RequestInit = { method, headers, signal };
      if (body !== undefined) init.body = body;
      response = await this.fetchImpl(this.baseUrl + path, init);
    } catch (cause) {
      if (options.signal?.aborted) throw cause;
      const timedOut = timeout.aborted;
      throw new OmniConnectorError(
        0,
        {
          code: timedOut ? "client_timeout" : "network_error",
          message: timedOut ? `request timed out after ${this.timeoutMs} ms` : "request could not be sent",
          category: timedOut ? "timeout" : "network_error",
          retryable: true,
        },
        options.requestId,
        { cause },
      );
    }

    const requestId = response.headers.get("X-Request-ID") ?? options.requestId;
    const text = await response.text();
    let payload: unknown;
    try {
      payload = text ? JSON.parse(text) : undefined;
    } catch {
      payload = undefined;
    }

    if (!response.ok) {
      const env = payload as Envelope | undefined;
      const error: NormalizedError = env?.error ?? {
        code: "http_error",
        message: `unexpected HTTP ${response.status} response`,
        category: response.status >= 500 ? "internal_error" : "provider_error",
        retryable: response.status >= 500,
      };
      throw new OmniConnectorError(response.status, error, env?.error?.requestId ?? requestId);
    }
    return payload as T;
  }
}

class Integrations {
  constructor(private readonly client: OmniConnectorClient) {}

  /** Integrations registered in the kernel */
  async list(options?: RequestOptions): Promise<IntegrationSummary[]> {
    const res = await this.client.request<{ integrations: IntegrationSummary[] }>("GET", "/v1/integrations", options);
    return res.integrations;
  }

  /** One integration, including its auth methods and operation definitions */
  get(integration: string, options?: RequestOptions): Promise<IntegrationDetail> {
    return this.client.request("GET", `/v1/integrations/${encodeURIComponent(integration)}`, options);
  }

  /** Capabilities an integration declares, with the permissions each requires */
  async capabilities(integration: string, options?: RequestOptions): Promise<Capability[]> {
    const res = await this.client.request<{ capabilities: Capability[] }>(
      "GET",
      `/v1/integrations/${encodeURIComponent(integration)}/capabilities`,
      options,
    );
    return res.capabilities;
  }
}

class Operations {
  constructor(private readonly client: OmniConnectorClient) {}

  /**
   * Submits and runs an operation. Resolves with the operation record even
   * when the operation itself failed — check `state`. Throws
   * OmniConnectorError only if the request was rejected (validation,
   * authorization, unknown integration, …).
   */
  create(request: CreateOperationRequest, options: CreateOperationOptions = {}): Promise<Operation> {
    const headers: Record<string, string> = {};
    if (options.idempotencyKey) headers["Idempotency-Key"] = options.idempotencyKey;
    return this.client.request("POST", "/v1/operations", { ...options, body: request, headers });
  }

  get(id: string, options?: RequestOptions): Promise<Operation> {
    return this.client.request("GET", `/v1/operations/${encodeURIComponent(id)}`, options);
  }

  /** The caller's operations, newest first (admins see all) */
  async list(options: RequestOptions & { limit?: number } = {}): Promise<Operation[]> {
    const query = options.limit !== undefined ? `?limit=${options.limit}` : "";
    const res = await this.client.request<{ operations: Operation[] }>("GET", `/v1/operations${query}`, options);
    return res.operations;
  }

  /**
   * Requests cancellation. Resolves with the operation in "cancel_requested";
   * the final state ("cancelled", or "unknown_outcome" for operations with
   * side effects) is set once the integration stops.
   */
  cancel(id: string, options?: RequestOptions): Promise<Operation> {
    return this.client.request("POST", `/v1/operations/${encodeURIComponent(id)}/cancel`, options);
  }

  /** Polls until the operation reaches a terminal state and returns it */
  async wait(id: string, options: WaitOptions = {}): Promise<Operation> {
    const interval = options.intervalMs ?? 1_000;
    const deadline = options.timeoutMs !== undefined ? Date.now() + options.timeoutMs : Infinity;
    for (;;) {
      const op = await this.get(id, options);
      if (isTerminal(op.state)) return op;
      if (Date.now() + interval > deadline) {
        throw new OmniConnectorError(0, {
          code: "wait_timeout",
          message: `operation ${id} did not finish within ${options.timeoutMs} ms (last state: ${op.state})`,
          category: "timeout",
          retryable: true,
        });
      }
      await sleep(interval, options.signal);
    }
  }
}

class AuditEvents {
  constructor(private readonly client: OmniConnectorClient) {}

  /** Audit events, newest first. Requires audit.read; non-admins see only their own. */
  async list(options: RequestOptions & { limit?: number } = {}): Promise<AuditEvent[]> {
    const query = options.limit !== undefined ? `?limit=${options.limit}` : "";
    const res = await this.client.request<{ events: AuditEvent[] }>("GET", `/v1/audit-events${query}`, options);
    return res.events;
  }
}

function sleep(ms: number, signal?: AbortSignal): Promise<void> {
  return new Promise((resolve, reject) => {
    if (signal?.aborted) return reject(signal.reason);
    const timer = setTimeout(() => {
      signal?.removeEventListener("abort", onAbort);
      resolve();
    }, ms);
    const onAbort = () => {
      clearTimeout(timer);
      reject(signal?.reason);
    };
    signal?.addEventListener("abort", onAbort, { once: true });
  });
}
